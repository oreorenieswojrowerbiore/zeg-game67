let currentPuzzle = null;

function checkRiddle() {
    const riddle = riddles[currentLevel];

    if (!riddle) {
        return;
    }

    if (
        player.x === riddle.x &&
        player.y === riddle.y &&
        !riddle.taken
    ) {
        openPuzzle();
    }
}

function openPuzzle() {
    currentPuzzle =
        PUZZLES[Math.floor(Math.random() * PUZZLES.length)];

    document.getElementById("puzzleQuestion").textContent =
        currentPuzzle.question;

    document.getElementById("answerA").textContent =
        currentPuzzle.answers[0];

    document.getElementById("answerB").textContent =
        currentPuzzle.answers[1];

    document.getElementById("puzzleBox").style.display = "flex";
}

function answerPuzzle(answerIndex) {
    const riddle = riddles[currentLevel];

    if (answerIndex === currentPuzzle.correct) {
        document.getElementById("goodPuzzleSound").play();

        if (hearts < 3) {
            hearts++;
            updateHearts();
        }
    } else {
        takeDamage();
    }

    riddle.taken = true;

    document.getElementById("puzzleBox").style.display = "none";

    renderLevel();
}

document.getElementById("answerA").addEventListener("click", function() {
    answerPuzzle(0);
});

document.getElementById("answerB").addEventListener("click", function() {
    answerPuzzle(1);
});